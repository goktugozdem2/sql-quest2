// Writes src/data/postgres-allowlist.json — the challenges PostgreSQL mode
// opens — from a run of every reference solution on SQLite and PGlite
// (scripts/pg/run-bank.mjs). Run it after changing the bank, a dataset or
// src/utils/pg-translate.js:
//
//   node scripts/pg/build-allowlist.mjs            # write the list
//   node scripts/pg/build-allowlist.mjs --check    # fail if it is stale
//
// Each entry is 'asis' (the reference runs on Postgres as written) or
// 'rewrite' (the app grades with pgExpectedSql's rewrite). On the list:
// unchanged, rewritten, rounding, text_numbers. Off it: nondeterministic
// (the reference does not decide its own answer), hand (needs a hand edit),
// sqlite_error. The full per-challenge report goes to
// docs/plans/postgres-mode-coverage-2026-11-22.md.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { runBank } from './run-bank.mjs';

const here = rel => fileURLToPath(new URL(rel, import.meta.url));
const OUT = here('../../src/data/postgres-allowlist.json');
const REPORT = here('../../docs/plans/postgres-mode-coverage-2026-11-22.md');
const ON_LIST = new Set(['unchanged', 'rewritten', 'rounding', 'text_numbers']);
const pgliteVersion = JSON.parse(readFileSync(here('../../node_modules/@electric-sql/pglite/package.json'), 'utf8')).version;

const { results, bankSize } = await runBank();
const counts = {};
for (const r of results) counts[r.status] = (counts[r.status] || 0) + 1;
const broken = results.filter(r => ON_LIST.has(r.status) && r.appRuns === false);
if (broken.length) {
  console.error('the app form of these rewrites does not run:', broken.map(r => r.id).join(', '));
  process.exit(1);
}
const challenges = {};
for (const r of [...results].sort((a, b) => a.id - b.id)) {
  if (ON_LIST.has(r.status)) challenges[r.id] = r.status === 'unchanged' ? 'asis' : 'rewrite';
}
const list = {
  _: 'Generated by scripts/pg/build-allowlist.mjs — do not hand-edit. PostgreSQL mode opens only these challenges.',
  pglite: pgliteVersion,
  bankSize,
  counts,
  challenges,
};
const json = JSON.stringify(list, null, 1) + '\n';

const pct = n => `${((100 * n) / bankSize).toFixed(1)}%`;
const rows = results.filter(r => !['unchanged'].includes(r.status))
  .sort((a, b) => a.id - b.id)
  .map(r => `| ${r.id} | ${r.status} | ${(r.rewrites || []).join(', ') || '—'} | ${(r.reason || '').replace(/\|/g, '\\|')} |`);
const rewriteUse = {};
for (const r of results) for (const w of r.rewrites || []) if (ON_LIST.has(r.status)) rewriteUse[w] = (rewriteUse[w] || 0) + 1;
const report = `# PostgreSQL mode — coverage of the bank (generated)

Generated by \`node scripts/pg/build-allowlist.mjs\` on PGlite ${pgliteVersion}. Do not hand-edit.
Plan and recommendation: [postgres-mode-2026-11-22.md](postgres-mode-2026-11-22.md).

| Status | Challenges | Share of ${bankSize} |
|---|---|---|
${Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} | ${pct(v)} |`).join('\n')}
| **on the allow-list** | **${Object.keys(challenges).length}** | **${pct(Object.keys(challenges).length)}** |

Rewrites used by challenges on the list:

| Rewrite | Challenges |
|---|---|
${Object.entries(rewriteUse).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k} | ${v} |`).join('\n')}

Every challenge that does not run unchanged:

| Id | Status | Rewrites | Note |
|---|---|---|---|
${rows.join('\n')}
`;

if (process.argv.includes('--check')) {
  const cur = readFileSync(OUT, 'utf8');
  if (cur !== json) { console.error('src/data/postgres-allowlist.json is stale: run node scripts/pg/build-allowlist.mjs'); process.exit(1); }
  console.log('allow-list up to date');
} else {
  writeFileSync(OUT, json);
  writeFileSync(REPORT, report);
  console.log(counts, `${Object.keys(challenges).length}/${bankSize} on the list`);
}
