#!/usr/bin/env node
/**
 * Writes src/data/app-data-slices.js — the few values the app needs from two
 * registries that exist for the static pages (2026-11-27, bundle slim).
 *
 *  - SOURCED_COMPANY_NAMES from src/data/company-interviews.js. The app only
 *    asks "does this company have a dated source for its process?"
 *    (companyHasSourcedFormat). The Set is computed from the registry's
 *    objects, so importing it pulled every format row, source title and URL
 *    (~55 kB minified, ~15.7 kB gzipped) into public/app.js — Rollup cannot
 *    tree-shake a value computed from them.
 *  - SQL_PATTERN_LINKS + PATTERN_FOR_MOCK_QUESTION from
 *    src/data/sql-patterns.js. The app reads a trap page's slug, short name
 *    and mock reference (the trap-page → Pro-mock door, the "read this trap"
 *    link); the page copy, queries and facts stay with the page generator.
 *
 * The values are computed by the registries' own exports, here at build time,
 * so nothing is re-typed. Runs first in `npm run build:jsx`; a registry edit
 * reaches the app on the next build. tests/bundle-slim.test.js fails when the
 * committed file differs from what this script writes.
 *
 *   node scripts/build-app-data-slices.mjs          # write (only if changed)
 *   node scripts/build-app-data-slices.mjs --check  # exit 1 if stale
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { SOURCED_COMPANY_NAMES } from '../src/data/company-interviews.js';
import { SQL_PATTERNS, PATTERN_FOR_MOCK_QUESTION } from '../src/data/sql-patterns.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'src/data/app-data-slices.js');

const json = (v) => JSON.stringify(v, null, 2);

export function renderAppDataSlices() {
  const links = SQL_PATTERNS.map(p => {
    const row = { slug: p.slug, short: p.short, mock: p.mock };
    if (p.alsoIn) row.alsoIn = p.alsoIn;
    return row;
  });
  return `// GENERATED by scripts/build-app-data-slices.mjs — do not edit. Edit
// src/data/company-interviews.js or src/data/sql-patterns.js and build.
// The app imports these slices instead of the registries so the pages' copy,
// sources and queries stay out of public/app.js (tests/bundle-slim.test.js).

// Companies with a dated source for their own process (company-interviews.js).
export const SOURCED_COMPANY_NAMES = new Set(${json([...SOURCED_COMPANY_NAMES])});

// The trap pages as the app reads them: slug, short name, mock reference(s)
// (sql-patterns.js SQL_PATTERNS).
export const SQL_PATTERN_LINKS = ${json(links)};

// Mock question id → the trap page that explains it (sql-patterns.js).
export const PATTERN_FOR_MOCK_QUESTION = ${json(PATTERN_FOR_MOCK_QUESTION)};
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = renderAppDataSlices();
  const prev = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (prev !== next) {
      console.error('src/data/app-data-slices.js is stale — run node scripts/build-app-data-slices.mjs');
      process.exit(1);
    }
  } else if (prev !== next) {
    fs.writeFileSync(OUT, next);
    console.log(`wrote ${path.relative(ROOT, OUT)}`);
  }
}
