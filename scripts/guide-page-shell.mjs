export function breadcrumb(name, url) {
  return { '@context': 'https://schema.org', '@type': 'BreadcrumbList', itemListElement: [
    { '@type': 'ListItem', position: 1, name: 'SQL Quest', item: `${SITE}/` },
    { '@type': 'ListItem', position: 2, name: 'SQL Interview Prep', item: `${SITE}/sql-interview-prep/` },
    { '@type': 'ListItem', position: 3, name, item: url },
  ] };
}

export function article({ headline, description, url, published }) {
  return { '@context': 'https://schema.org', '@type': 'Article', headline, description, url,
    mainEntityOfPage: url, image: `${SITE}/og-image.png`, inLanguage: 'en',
    datePublished: published, dateModified: published, author: ORG, publisher: ORG };
}

export function faqPage(faq) {
  return { '@context': 'https://schema.org', '@type': 'FAQPage',
    mainEntity: faq.map(([q, a]) => ({ '@type': 'Question', name: q, acceptedAnswer: { '@type': 'Answer', text: a } })) };
}

export function faqSection(faq) {
  return `  <section class="faq">
    <h2 class="fd">Questions</h2>
${faq.map(([q, a]) => `    <h3>${esc(q)}</h3>\n    <p>${esc(a)}</p>`).join('\n')}
  </section>`;
}

/** Add (or replace) one URL between <!-- key:start --> and <!-- key:end --> in public/sitemap.xml. */
export function writeSitemapBlock(key, slug, published, { priority = '0.7' } = {}) {
  const file = path.join(ROOT, 'public', 'sitemap.xml');
  let xml = fs.readFileSync(file, 'utf8');
  xml = xml.replace(new RegExp(`\\s*<!-- ${key}:start -->[\\s\\S]*?<!-- ${key}:end -->`), '');
  // Placeholder date; scripts/sitemap-lastmod.mjs rewrites <lastmod> from the built page's hash.
  const block = `\n  <!-- ${key}:start -->\n  <url>\n    <loc>${SITE}/${slug}/</loc>\n    <lastmod>${published}</lastmod>\n    <changefreq>monthly</changefreq>\n    <priority>${priority}</priority>\n  </url>\n  <!-- ${key}:end -->`;
  xml = xml.replace('</urlset>', `${block}\n</urlset>`);
  fs.writeFileSync(file, xml);
}
