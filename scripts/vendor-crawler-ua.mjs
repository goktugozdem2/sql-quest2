#!/usr/bin/env node
// Vendors the crawler user-agent list (monperrus/crawler-user-agents, MIT)
// into the two trackers, 2026-11-24.
//
// Why: the landing tracker and the app drop a user agent that names itself
// a bot (BOT_UA_RE in src/utils/bot-signals.js, isBot() in src/track.js).
// That regex is hand-kept and misses fetchers with no "bot" in the name:
// over the 7 days to 2026-11-24, 155 of 972 new landing people were
// GoogleOther (145) or Google-NotebookLM (10), and none of the 1,129 such
// people over all time ever opened the app. The upstream list names both.
//
// What: the package is an exact-pinned devDependency; this script keeps
// only the patterns BOT_UA_RE does not already cover (a pattern whose every
// match contains one of our words is dropped — both trackers have already
// thrown that row away before any stamp is read), and writes them to
//   src/data/crawler-user-agents.js   (src/utils/crawler-ua.js, the testable half)
//   src/track.js between the crawler-user-agents:start/end markers
// with the upstream version and the sha256 of the JSON it read.
// Measurement only: track.js STAMPS `cuaBot` on landing_view, never drops on it.
//
// Run after bumping the pin:  node scripts/vendor-crawler-ua.mjs
// Check only (used by tests):  node scripts/vendor-crawler-ua.mjs --check
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { BOT_UA_RE } from '../src/utils/bot-signals.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PKG_DIR = path.join(ROOT, 'node_modules', 'crawler-user-agents');
const DATA_OUT = path.join(ROOT, 'src', 'data', 'crawler-user-agents.js');
const TRACK = path.join(ROOT, 'src', 'track.js');
const START = '// crawler-user-agents:start (generated by scripts/vendor-crawler-ua.mjs — do not hand-edit)';
const END = '// crawler-user-agents:end';

// True only when every string the pattern can match contains a BOT_UA_RE
// word. Conservative: any alternation, group, class, quantifier other than
// `+`, or escape other than a literal punctuation one keeps the pattern.
export function coveredByOurRegex(pattern) {
  if (/[|?*()[\]{}]/.test(pattern)) return false;
  const lit = pattern.replace(/^\^/, '').replace(/\$$/, '');
  if (/\\[^/.\- _:;]/.test(lit)) return false;
  return BOT_UA_RE.test(lit.replace(/\\(.)/g, '$1'));
}

export function vendor() {
  const raw = fs.readFileSync(path.join(PKG_DIR, 'crawler-user-agents.json'));
  const version = JSON.parse(fs.readFileSync(path.join(PKG_DIR, 'package.json'), 'utf8')).version;
  const sha256 = crypto.createHash('sha256').update(raw).digest('hex');
  const list = JSON.parse(raw.toString('utf8'));
  const patterns = list.map(e => e.pattern).filter(p => !coveredByOurRegex(p));
  for (const p of patterns) new RegExp(p); // throws on a pattern JS cannot compile
  const meta = { version, sha256, upstream: list.length, kept: patterns.length };

  const dataSrc = `// GENERATED by scripts/vendor-crawler-ua.mjs — do not hand-edit.
// crawler-user-agents ${version} (MIT, https://github.com/monperrus/crawler-user-agents),
// sha256 of crawler-user-agents.json: ${sha256}
// ${patterns.length} of ${list.length} patterns: the ones BOT_UA_RE does not already cover.
export const CRAWLER_UA_META = ${JSON.stringify(meta)};
export const CRAWLER_UA_PATTERNS = ${JSON.stringify(patterns)};
`;

  const block = `${START}
  // crawler-user-agents ${version}, sha256 ${sha256.slice(0, 16)}…, ${patterns.length} of ${list.length} patterns.
  var CUA_PATTERNS = ${JSON.stringify(patterns)};
  ${END}`;
  const track = fs.readFileSync(TRACK, 'utf8');
  const a = track.indexOf(START);
  const b = track.indexOf(END);
  if (a < 0 || b < a) throw new Error('src/track.js: crawler-user-agents markers missing');
  const trackOut = track.slice(0, a) + block + track.slice(b + END.length);
  return { meta, dataSrc, trackOut };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const { meta, dataSrc, trackOut } = vendor();
  if (process.argv.includes('--check')) {
    const ok = fs.readFileSync(DATA_OUT, 'utf8') === dataSrc && fs.readFileSync(TRACK, 'utf8') === trackOut;
    console.log(ok ? 'crawler-user-agents: vendored copy is current' : 'crawler-user-agents: STALE — run node scripts/vendor-crawler-ua.mjs');
    process.exit(ok ? 0 : 1);
  }
  fs.writeFileSync(DATA_OUT, dataSrc);
  fs.writeFileSync(TRACK, trackOut);
  console.log(`crawler-user-agents ${meta.version}: kept ${meta.kept} of ${meta.upstream} patterns`);
}
