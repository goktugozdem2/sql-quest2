#!/usr/bin/env node
// build-emails — renders the React Email templates in emails/ into static
// template strings the Deno edge functions import (2026-11-25).
//
// Edge functions run on Deno and must not carry a React runtime, and the app
// bundle must not carry email code. So React Email runs here, at build time
// only: each template is rendered ONCE with its {{slot}} placeholders as
// props, to HTML and to plain text, and written to
// supabase/functions/<fn>/template.generated.ts. The function fills the slots
// per recipient. Deterministic: the same source renders the same file
// (tests/activated-note-template.test.js fails on drift).
//
//   node scripts/build-emails.mjs          write every generated template
//   node scripts/build-emails.mjs --check  exit 1 if a committed one is stale
//
// The deps (@react-email/components, react, react-dom) are devDependencies;
// nothing under src/ imports them, so `npm run size` never sees them.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const TEMPLATES = [
  {
    source: 'emails/activated-note.tsx',
    out: 'supabase/functions/activated-note/template.generated.ts',
    prefix: 'ACTIVATED_NOTE',
  },
];

// Transpile the .tsx with Vite's own transformer (already a devDependency)
// and import it from a cache file inside node_modules, so its bare imports
// (react, @react-email/components) resolve from the repo.
async function loadTemplate(source) {
  const { transformWithOxc } = await import('vite');
  const file = path.join(ROOT, source);
  const { code } = await transformWithOxc(fs.readFileSync(file, 'utf8'), file, {
    lang: 'tsx', jsx: { runtime: 'automatic' },
  });
  const dir = path.join(ROOT, 'node_modules/.cache/build-emails');
  fs.mkdirSync(dir, { recursive: true });
  const tmp = path.join(dir, `${path.basename(source, '.tsx')}-${process.pid}-${Date.now()}.mjs`);
  fs.writeFileSync(tmp, code);
  try {
    return await import(pathToFileURL(tmp).href);
  } finally {
    fs.rmSync(tmp, { force: true });
  }
}

export async function renderTemplateModule(t) {
  const mod = await loadTemplate(t.source);
  const { render } = await import('@react-email/components');
  const React = await import('react');
  const el = React.createElement(mod.default, { ...mod.SLOTS });
  const html = await render(el);
  const text = await render(el, { plainText: true });
  const slots = Object.keys(mod.SLOTS);
  for (const s of slots) {
    if (!html.includes(`{{${s}}}`)) throw new Error(`${t.source}: slot {{${s}}} missing from the HTML render`);
  }
  return [
    `// GENERATED by scripts/build-emails.mjs from ${t.source} — do not edit.`,
    '// Edit the .tsx, then run `node scripts/build-emails.mjs` (also part of `npm run build`).',
    '// Placeholders are {{slot}}; letter.ts fills them (HTML-escaped in the HTML,',
    '// verbatim in the text) and refuses to send a letter with one left over.',
    '',
    `export const ${t.prefix}_SLOTS = ${JSON.stringify(slots)} as const`,
    '',
    `export const ${t.prefix}_HTML = ${JSON.stringify(html)}`,
    '',
    `export const ${t.prefix}_TEXT = ${JSON.stringify(text)}`,
    '',
  ].join('\n');
}

async function main() {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const t of TEMPLATES) {
    const next = await renderTemplateModule(t);
    const out = path.join(ROOT, t.out);
    const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : null;
    if (prev === next) continue;
    if (check) { console.error(`stale: ${t.out} (run node scripts/build-emails.mjs)`); stale++; continue; }
    fs.writeFileSync(out, next);
    console.log(`wrote ${t.out}`);
  }
  if (stale) process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(err => { console.error(err); process.exit(1); });
}
